COLUNAS_RELATORIO = [
    "sinistro",
    "caso_id",
    "caso_status",
    "resultado",
    "mensagem",
    "sucesso",
    "processado_em"
]

def log(nr_sinistro, codigo, mensagem, sucesso):
    status = "OK" if sucesso else "ERRO"
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    print(f"[{timestamp}] [{status}] Sinistro:{nr_sinistro} Cod:{codigo} - {mensagem}")

def log_progresso(indice_atual, total):
    percentual = (indice_atual / total * 100) if total else 100
    print(f"[PROGRESSO] {indice_atual}/{total} processados ({percentual:.2f}%)")

def montar_resultado(nr_sinistro, sucesso, resultado, mensagem, caso_id="", caso_status=""):
    return {
        "sinistro": nr_sinistro,
        "caso_id": caso_id,
        "caso_status": caso_status,
        "resultado": resultado,
        "mensagem": mensagem,
        "sucesso": "SIM" if sucesso else "NAO",
        "processado_em": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    }

def carregar_resultados_csv(caminho_arquivo):
    resultados = {}

    if not caminho_arquivo.exists():
        return resultados

    with caminho_arquivo.open("r", newline="", encoding="utf-8-sig") as arquivo_csv:
        leitor = csv.DictReader(arquivo_csv)

        for linha in leitor:
            sinistro = str(linha.get("sinistro", "")).strip()
            if sinistro:
                resultados[sinistro] = {
                    coluna: linha.get(coluna, "")
                    for coluna in COLUNAS_RELATORIO
                }

    return resultados

def salvar_resultado_csv(caminho_arquivo, resultado):
    arquivo_existe = caminho_arquivo.exists()

    with caminho_arquivo.open("a", newline="", encoding="utf-8") as arquivo_csv:
        escritor = csv.DictWriter(arquivo_csv, fieldnames=COLUNAS_RELATORIO)

        if not arquivo_existe:
            escritor.writeheader()

        escritor.writerow({coluna: resultado.get(coluna, "") for coluna in COLUNAS_RELATORIO})

def processar_sinistro(nr_sinistro):
    try:
        return cancelar_caso(nr_sinistro)
    except Exception as exc:
        mensagem = f"Erro inesperado: {str(exc)}"
        log(nr_sinistro, 30029, mensagem, False)
        return montar_resultado(nr_sinistro, False, "erro_inesperado", mensagem)

def cancelar_caso(nr_sinistro):
    log(nr_sinistro, 30029, f"Consulta caso no BPM - {nr_sinistro}", True)

    caso = consultar_caso(nr_sinistro)

    if "error" in caso:
        log(nr_sinistro, 30029, caso["error"], False)
        return montar_resultado(nr_sinistro, False, "erro_consulta", caso["error"])

    if caso.get("caso_status") == "5":
        return abortar_bpm(caso["caso_id"], nr_sinistro, caso["caso_status"])

    mensagem = f"Sem casos para cancelamento no BPM - {nr_sinistro}"
    log(nr_sinistro, 30029, mensagem, True)
    return montar_resultado(
        nr_sinistro,
        True,
        "sem_cancelamento",
        mensagem,
        caso_id=caso.get("caso_id", ""),
        caso_status=caso.get("caso_status", "")
    )

def consultar_caso(nr_sinistro):

    url = "http://toovasp019/BPMTOO/WebServices/QuerySOA.asmx"

    headers = {
        "Content-Type": "text/xml; charset=utf-8",
        "SOAPAction": "http://tempuri.org/QueryCasesAsString"
    }

    data = f"""<?xml version="1.0" encoding="utf-8"?>
    <soap:Envelope xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
    xmlns:xsd="http://www.w3.org/2001/XMLSchema"
    xmlns:soap="http://schemas.xmlsoap.org/soap/envelope/">
        <soap:Body>
            <QueryCasesAsString xmlns="http://tempuri.org/">
                <sxml>
                    <![CDATA[
                    <BizAgiWSParam>
                        <Domain>domain</Domain>
                        <UserName>admon</UserName>
                        <QueryParams>
                            <Internals>
                                <Internal Name="NUMSinistro" Include="false">1007700108022</Internal>
                            </Internals>
                            <XPaths>
                                <XPath Path="TratamentoDeSinistros.Sinistro.NUMSinistro"
                                Include="false"
                                Approx="false">{nr_sinistro}</XPath>
                            </XPaths>
                        </QueryParams>
                        <Parameters>
                            <Parameter Name="nameEnt">TratamentoDeSinistros</Parameter>
                            <Parameter Name="page">1</Parameter>
                            <Parameter Name="pageSize">100</Parameter>
                        </Parameters>
                    </BizAgiWSParam>
                    ]]>
                </sxml>
            </QueryCasesAsString>
        </soap:Body>
    </soap:Envelope>"""

    try:

        response = requests.post(url, headers=headers, data=data, timeout=30)
        response.raise_for_status()

        root = ET.fromstring(response.text)

        namespace = {
            "soap": "http://schemas.xmlsoap.org/soap/envelope/",
            "tempuri": "http://tempuri.org/"
        }

        result = root.find(".//tempuri:QueryCasesAsStringResult", namespaces=namespace)

        if result is not None:

            result_text = result.text
            bizagi_response = ET.fromstring(result_text)

            rows = bizagi_response.find(".//Rows")

            if rows is not None:

                for row in rows.findall("Row"):

                    radnumber = row.find("./Column[@Name='RADNUMBER']")
                    idcasestate = row.find("./Column[@Name='IDCASESTATE']")

                    if radnumber is not None and idcasestate is not None:

                        return {
                            "caso_id": str(radnumber.text),
                            "caso_status": str(idcasestate.text)
                        }

        return {"error": "Caso não encontrado"}

    except requests.RequestException as e:
        return {"error": f"Erro na requisição: {str(e)}"}

    except ET.ParseError as e:
        return {"error": f"Erro ao processar XML: {str(e)}"}

def abortar_bpm(caso_id, nr_sinistro, caso_status):

    url = "http://toovasp019/BPMTOO/webservices/workflowenginesoa.asmx"

    headers = {
        "Content-Type": "text/xml; charset=utf-8",
        "SOAPAction": "http://tempuri.org/abortCasesAsString"
    }

    data = f"""<?xml version="1.0" encoding="utf-8"?>
    <soap:Envelope xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
    xmlns:xsd="http://www.w3.org/2001/XMLSchema"
    xmlns:soap="http://schemas.xmlsoap.org/soap/envelope/">
    <soap:Body>
    <abortCasesAsString xmlns="http://tempuri.org/">
    <info>
    <![CDATA[
    <BizAgiWSParam>
    <domain>domain</domain>
    <userName>admon</userName>
    <cases>
    <case>
    <idCase>{caso_id}</idCase>
    <abortReason>Tratado pelo motor.</abortReason>
    </case>
    </cases>
    </BizAgiWSParam>
    ]]>
    </info>
    </abortCasesAsString>
    </soap:Body>
    </soap:Envelope>"""

    try:
        response = requests.post(url, headers=headers, data=data, timeout=30)
        response.raise_for_status()
    except requests.RequestException as exc:
        mensagem = f"Erro ao encerrar caso {caso_id}: {str(exc)}"
        log(nr_sinistro, 30029, mensagem, False)
        return montar_resultado(nr_sinistro, False, "erro_cancelamento", mensagem, caso_id, caso_status)

    mensagem = f"Encerrar caso {caso_id} BPM - {nr_sinistro}"
    log(nr_sinistro, 30029, mensagem, True)
    return montar_resultado(nr_sinistro, True, "cancelado", mensagem, caso_id, caso_status)

def _coluna_excel(indice):
    coluna = ""

    while indice > 0:
        indice, resto = divmod(indice - 1, 26)
        coluna = chr(65 + resto) + coluna

    return coluna

def _valor_para_celula(valor):
    if isinstance(valor, (int, float)) and not isinstance(valor, bool):
        return f"<c><v>{valor}</v></c>"

    texto = escape("" if valor is None else str(valor))
    return f'<c t="inlineStr"><is><t>{texto}</t></is></c>'

def salvar_relatorio_xlsx(resultados, caminho_arquivo):
    colunas = COLUNAS_RELATORIO

    linhas = [colunas]
    linhas.extend([[resultado.get(coluna, "") for coluna in colunas] for resultado in resultados])

    ultima_coluna = _coluna_excel(len(colunas))
    ultima_linha = max(len(linhas), 1)
    linhas_xml = []

    for indice_linha, linha in enumerate(linhas, start=1):
        celulas = []
        for indice_coluna, valor in enumerate(linha, start=1):
            referencia = f"{_coluna_excel(indice_coluna)}{indice_linha}"
            celulas.append(f"<c r=\"{referencia}\"{_valor_para_celula(valor)[2:]}")

        linhas_xml.append(f"<row r=\"{indice_linha}\">{''.join(celulas)}</row>")

    worksheet_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
        f'<dimension ref="A1:{ultima_coluna}{ultima_linha}"/>'
        '<sheetViews><sheetView workbookViewId="0"/></sheetViews>'
        '<sheetFormatPr defaultRowHeight="15"/>'
        '<sheetData>'
        f'{"".join(linhas_xml)}'
        '</sheetData>'
        '</worksheet>'
    )

    workbook_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
        'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
        '<sheets><sheet name="Resultados" sheetId="1" r:id="rId1"/></sheets>'
        '</workbook>'
    )

    workbook_rels_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" '
        'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" '
        'Target="worksheets/sheet1.xml"/>'
        '</Relationships>'
    )

    root_rels_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" '
        'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
        'Target="xl/workbook.xml"/>'
        '</Relationships>'
    )

    content_types_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/xl/workbook.xml" '
        'ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
        '<Override PartName="/xl/worksheets/sheet1.xml" '
        'ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
        '</Types>'
    )

    with ZipFile(caminho_arquivo, "w", ZIP_DEFLATED) as arquivo_xlsx:
        arquivo_xlsx.writestr("[Content_Types].xml", content_types_xml)
        arquivo_xlsx.writestr("_rels/.rels", root_rels_xml)
        arquivo_xlsx.writestr("xl/workbook.xml", workbook_xml)
        arquivo_xlsx.writestr("xl/_rels/workbook.xml.rels", workbook_rels_xml)
        arquivo_xlsx.writestr("xl/worksheets/sheet1.xml", worksheet_xml)
def processar_sinistros(lista_sinistros, caminho_csv=None, caminho_xlsx=None, max_workers=10):
    total = len(lista_sinistros)
    caminho_csv = Path(caminho_csv) if caminho_csv else Path.cwd() / "relatorio_cancelamento_bpm.csv"
    resultados_existentes = carregar_resultados_csv(caminho_csv)
    resultados = dict(resultados_existentes)
    concluidos = 0

    print(f"Iniciando processamento de {total} sinistros")

    sinistros_pendentes = []

    for nr_sinistro in lista_sinistros:
        sinistro = str(nr_sinistro)

        if sinistro in resultados_existentes:
            log(sinistro, 30029, "Sinistro ja processado no CSV. Pulando para o proximo.", True)
            concluidos += 1
            log_progresso(concluidos, total)
            continue

        sinistros_pendentes.append(sinistro)

    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        futuros = {
            executor.submit(processar_sinistro, nr_sinistro): nr_sinistro
            for nr_sinistro in sinistros_pendentes
        }

        for futuro in as_completed(futuros):
            resultado = futuro.result()
            resultados[resultado["sinistro"]] = resultado
            salvar_resultado_csv(caminho_csv, resultado)
            concluidos += 1
            log_progresso(concluidos, total)

    caminho_relatorio = Path(caminho_xlsx) if caminho_xlsx else Path.cwd() / (
        f"relatorio_cancelamento_bpm_{datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
    )
    resultados_ordenados = list(resultados.values())
    salvar_relatorio_xlsx(resultados_ordenados, caminho_relatorio)

    sucessos = sum(1 for resultado in resultados_ordenados if resultado["sucesso"] == "SIM")
    falhas = len(resultados_ordenados) - sucessos

    print("Processamento finalizado")
    print(f"Sucessos: {sucessos} | Falhas: {falhas}")
    print(f"Checkpoint CSV: {caminho_csv}")
    print(f"Relatorio gerado em: {caminho_relatorio}")

    return resultados_ordenados, caminho_relatorio

