import json
import os
from concurrent.futures import ThreadPoolExecutor

import requests
from dotenv import load_dotenv
from openpyxl import Workbook
from pymongo import MongoClient

load_dotenv()

MONGO_URI = os.getenv("PRD_MONGO_SA_EAST")
DB_NAME = "SinistrosMicroService"

COLLECTION_SEGURADO = "AvisoSinistro"
COLLECTION_ANEXOS = "AvisoSinistroAnexo"

URL = "http://i4pro.tooseguros.com.br/i4protoo_prd/erpws/run/Sinistro/ConsultaDetalheSinistro"

def consultar_sinistro(num_sinistro):
    headers = {
        "Content-Type": "application/json"
    }

    payload = {
        "numSinistro": num_sinistro,
        "dvUserAdmin": True
    }

    try:
        resp = requests.post(URL, headers=headers, json=payload, timeout=30)

        if resp.status_code != 200:
            print(f"Erro API {num_sinistro}: {resp.status_code}")
            return None

        data = resp.json()

        return data.get("regulacao", {}).get("numeroCnpjCpfSinistrado")

    except Exception as e:
        print(f"Erro request {num_sinistro}: {e}")
        return None

def buscar_protocolos(collection, cpf_cnpj):
    cpf_cnpj = "".join(filter(str.isdigit, str(cpf_cnpj or "")))
    if cpf_cnpj:
        cpf_cnpj = cpf_cnpj.zfill(11 if len(cpf_cnpj) <= 11 else 14)

    resultados = collection.find(
        {"Segurado.CpfCnpj": cpf_cnpj},
        {"Protocolo": 1}
    )

    return [r.get("Protocolo") for r in resultados if r.get("Protocolo")]

def buscar_anexos(collection, protocolos):
    if not protocolos:
        return []

    query = {
        "Protocolo": {"$in": protocolos},
        "$or": [
            {"Key": {"$regex": "CERTIDAO_OBITO", "$options": "i"}},
            {"Key": {"$regex": "_CO_", "$options": "i"}}
        ]
    }

    return list(collection.find(query))

def processar_sinistro(sinistro, col_seg, col_anexo):
    print(f"Processando {sinistro}")

    cpf_cnpj = consultar_sinistro(sinistro)

    if not cpf_cnpj:
        return [[sinistro, False, None, None]]

    protocolos = buscar_protocolos(col_seg, cpf_cnpj)
    anexos = buscar_anexos(col_anexo, protocolos)

    if anexos:
        return [
            [
                sinistro,
                True,
                anexo.get("Key"),
                anexo.get("DataInclusaoAnexo")
            ]
            for anexo in anexos
        ]

    return [[sinistro, False, None, None]]

def processar_sinistros(lista_sinistros):

    client = MongoClient(MONGO_URI)
    db = client[DB_NAME]

    col_seg = db[COLLECTION_SEGURADO]
    col_anexo = db[COLLECTION_ANEXOS]

    wb = Workbook()
    ws = wb.active
    ws.append(["Sinistro", "Sucesso", "Key", "DataInclusaoAnexo"])

    max_workers = min(10, len(lista_sinistros)) or 1

    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        for linhas in executor.map(
            lambda sinistro: processar_sinistro(sinistro, col_seg, col_anexo),
            lista_sinistros
        ):
            for linha in linhas:
                ws.append(linha)

    wb.save("resultado.xlsx")
    print("Arquivo gerado: resultado.xlsx")

