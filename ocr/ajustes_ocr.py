def verificar_e_inserir_arquivos(nome_arquivos):
    client = MongoClient(os.getenv("PRD_MONGO_SA_EAST"))
    db = client['OCR']

    collection_resposta = db['AtomicLog']
    collection_arquivos = db['TipificarArquivo']

    for nome_arquivo in nome_arquivos:
        resposta = collection_resposta.find_one({"NomeArquivo": nome_arquivo, "CasoId": {"$ne": None}})

        if resposta:
            caso_id = resposta.get("CasoId")
            arquivo_existente = collection_arquivos.find_one({"NomeArquivo": nome_arquivo})
            id = str(uuid.uuid4())
            if not arquivo_existente:
                documento_novo = {
                    "_id": id,
                    "Id": id,
                    "Region": "sa-east-1",
                    "Bucket": "auditlogprd",
                    "Key": f"TemporaryFiles/{nome_arquivo}",
                    "NomeArquivo": nome_arquivo,
                    "PerfilTipificacao": "Nova Arquitetura",
                    "CodigoReferencia": str(caso_id),
                    "CasoId": str(caso_id),
                    "Callback": f"https://open-api.tooseguros.com.br/bizagi/v1/callbackOcr/{caso_id}",
                    "StatusProcessamento": 1
                }

                collection_arquivos.insert_one(documento_novo)
                print(f'Arquivo "{nome_arquivo}" inserido na coleção de arquivos.')

    client.close()

