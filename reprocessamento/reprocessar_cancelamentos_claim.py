import os
from dotenv import load_dotenv
from datetime import datetime

import requests
from pymongo import MongoClient

load_dotenv()

MONGO_URI = os.getenv("PRD_MONGO_URI")
DB_NAME = "ClaimEngine"

COLLECTION = "Notification"

API_URL = os.getenv("CLAIM_ENGINE_API_PRD") + "/api/v1/Notification/Cancel"

TOKEN = os.getenv("FLOW_TOKEN")

def processar_flows(flow_ids):

    client = MongoClient(MONGO_URI)
    db = client[DB_NAME]
    collection = db[COLLECTION]

    resultados = []

    for flow_id in flow_ids:

        print(f"Processando flowId: {flow_id}")

        try:
            doc = collection.find_one({"flowId": flow_id})

            if not doc:
                print(f"[ERRO] flowId não encontrado: {flow_id}")
                resultados.append({
                    "flowId": flow_id,
                    "status": "NOT_FOUND"
                })
                continue

            collection.update_one(
                {"_id": doc["_id"]},
                {
                    "$set": {
                        "integrationStatus": "Pending",
                        "status": "Pending",
                        "UpdatedAt": datetime.utcnow()
                    }
                }
            )

            cancellation = doc.get("cancellation", {})

            reason_code = cancellation.get("reasonCode")
            cancellation_note = cancellation.get("cancellationNote")

            payload = {
                "flowId": flow_id,
                "cancellationReasonCode": reason_code,
                "cancellationNote": cancellation_note,
                "requestorCommunication": True
            }

            headers = {
                "Authorization": f"Bearer {TOKEN}",
                "Content-Type": "application/json",
                "x-auth-appname":"claim-engine-api"
            }

            response = requests.post(
                API_URL,
                headers=headers,
                json=payload,
                timeout=30
            )

            if response.status_code == 200:
                status_proc = "SUCCESS"
            else:
                status_proc = f"ERROR_{response.status_code}"

            resultados.append({
                "flowId": flow_id,
                "status": status_proc,
                "response": response.text
            })

            print(f"[OK] {flow_id} -> {status_proc}")

        except Exception as e:
            print(f"[EXCEPTION] {flow_id}: {str(e)}")

            resultados.append({
                "flowId": flow_id,
                "status": "EXCEPTION",
                "error": str(e)
            })

    return resultados

